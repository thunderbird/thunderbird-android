package net.thunderbird.piisafe.compiler.ir

import net.thunderbird.piisafe.compiler.PiiSafePluginKey
import net.thunderbird.piisafe.compiler.ir.transformer.ToStringOverridePiiSafeTransformer
import org.jetbrains.kotlin.backend.common.extensions.IrGenerationExtension
import org.jetbrains.kotlin.backend.common.extensions.IrPluginContext
import org.jetbrains.kotlin.ir.declarations.IrDeclarationOrigin
import org.jetbrains.kotlin.ir.declarations.IrModuleFragment
import org.jetbrains.kotlin.ir.visitors.transformChildrenVoid

internal class ToStringOverridePiiSafeBodyGenerator : IrGenerationExtension {
    companion object {
        /**
         * Declaration origin marker for toString() methods generated by the Pii-safe plugin.
         *
         * Used to identify and track IR declarations that have been synthesized by this plugin,
         * enabling proper handling during the transformation phase.
         */
        val Origin: IrDeclarationOrigin.GeneratedByPlugin = IrDeclarationOrigin.GeneratedByPlugin(PiiSafePluginKey)
    }

    override fun generate(moduleFragment: IrModuleFragment, pluginContext: IrPluginContext) {
        moduleFragment.transformChildrenVoid(transformer = ToStringOverridePiiSafeTransformer(pluginContext))
    }
}
